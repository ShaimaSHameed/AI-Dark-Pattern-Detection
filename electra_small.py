def predict_texts(texts_list, return_details=False):
    """
    Predict dark pattern category.

    Args:
        texts_list: List of input prompts
        return_details: If True, return detailed prediction info

    Returns:
        List of predictions (or detailed dicts)
    """
    s_feats = []
    for t in texts_list:
        tb = TextBlob(t)
        vd = vader.polarity_scores(t)
        s_feats.append([
            tb.sentiment.polarity, tb.sentiment.subjectivity,
            vd['neg'], vd['neu'], vd['pos'], vd['compound']
        ])
    s_feats = np.array(s_feats, dtype=np.float32)
    emb = batch_encode_texts(texts_list)
    X_ = np.concatenate([emb, s_feats], axis=1)
    X_scaled = scaler.transform(X_)

    probs = clf.predict_proba(X_scaled)

    results = []
    for prob_row in probs:
        sorted_idx = np.argsort(prob_row)[::-1]
        max_prob = prob_row[sorted_idx[0]]
        margin = max_prob - prob_row[sorted_idx[1]]
        prediction = le.classes_[sorted_idx[0]]

        if return_details:
            results.append({
                'prediction': prediction,
                'confidence': float(max_prob),
                'margin': float(margin),
                'is_dark_pattern': prediction != 'neutral',
                'top_3': [(le.classes_[sorted_idx[j]], float(prob_row[sorted_idx[j]]))
                          for j in range(min(3, len(sorted_idx)))]
            })
        else:
            results.append(prediction)
    return results

