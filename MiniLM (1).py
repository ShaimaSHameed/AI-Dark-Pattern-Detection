def extract_sentiment_features(texts):
    feats = []
    for t in tqdm(texts, desc="Sentiment"):
        tb = TextBlob(t)
        vd = vader.polarity_scores(t)
        feats.append([
            tb.sentiment.polarity,
            tb.sentiment.subjectivity,
            vd["neg"], vd["neu"], vd["pos"], vd["compound"]
        ])
    return np.array(feats, dtype=np.float32)

def batch_encode_texts(texts, batch_size=32):
    outputs = []
    with torch.no_grad():
        for i in tqdm(range(0, len(texts), batch_size), desc="Embeddings"):
            batch = texts[i:i+batch_size]
            enc = tokenizer(batch, padding=True, truncation=True,
                            max_length=256, return_tensors="pt")
            input_ids = enc["input_ids"].to(device)
            attention = enc["attention_mask"].to(device)

            out = backbone(input_ids=input_ids, attention_mask=attention)
            last_hidden = out.last_hidden_state

            mask = attention.unsqueeze(-1).expand(last_hidden.size()).float()
            summed = torch.sum(last_hidden * mask, dim=1)
            counts = torch.clamp(mask.sum(dim=1), min=1e-9)

            outputs.append((summed / counts).cpu().numpy())
    return np.vstack(outputs)

def extract_all_features(texts):
    return np.concatenate([
        batch_encode_texts(texts),
        extract_sentiment_features(texts)
    ], axis=1)

