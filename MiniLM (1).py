def extract_features(text_list, batch_size=32):
    all_embeddings = []
    all_sentiments = []

    with torch.no_grad():
        for i in range(0, len(text_list), batch_size):
            batch = text_list[i:i+batch_size]
            enc = tokenizer(batch, padding=True, truncation=True,
                            return_tensors="pt", max_length=256).to(device)

            out = encoder(**enc).last_hidden_state
            mask = enc["attention_mask"].unsqueeze(-1).float()
            pooled = (out * mask).sum(dim=1) / mask.sum(dim=1)
            all_embeddings.append(pooled.cpu().numpy())

    # Sentiment features
    for t in text_list:
        tb = TextBlob(t)
        vd = vader.polarity_scores(t)
        all_sentiments.append([
            tb.sentiment.polarity,
            tb.sentiment.subjectivity,
            vd['neg'], vd['neu'], vd['pos'], vd['compound']
        ])

    emb = np.vstack(all_embeddings)
    sent = np.array(all_sentiments)
    return np.concatenate([emb, sent], axis=1)

