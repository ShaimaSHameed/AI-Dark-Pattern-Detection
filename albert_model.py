# 1. Get CLS embeddings for raw text
def get_embeddings(texts):
    model_a.eval()
    out = []
    with torch.no_grad():
        for i in range(0, len(texts), 32):
            batch = texts[i:i+32]
            enc = tokenizer(
                batch,
                padding=True,
                truncation=True,
                max_length=128,
                return_tensors="pt"
            ).to(device)

            outputs = model_a.albert(**enc)
            cls = outputs.last_hidden_state[:, 0, :]
            out.append(cls.cpu().numpy())
    return np.vstack(out)

# 2. ALBERT probabilities
def get_albert_probs(texts):
    model_a.eval()
    probs = []
    with torch.no_grad():
        for i in range(0, len(texts), 32):
            batch = texts[i:i+32]
            enc = tokenizer(
                batch,
                padding=True,
                truncation=True,
                max_length=128,
                return_tensors="pt"
            ).to(device)

            logits = model_a(**enc).logits
            probs.append(F.softmax(logits, dim=-1).cpu().numpy())

    return np.vstack(probs)

# 3. Logistic Regression probabilities
def get_lr_probs(texts):
    emb = get_embeddings(texts)
    emb_noisy = emb + np.random.normal(0, noise_std, emb.shape)
    p = pca.transform(emb_noisy)
    s = scaler.transform(p)
    return lr.predict_proba(s)

# 4. Hybrid prediction rules
def hybrid_predict(texts):
    pa = get_albert_probs(texts)
    pb = get_lr_probs(texts)

    final = []

    for i, t in enumerate(texts):
        a_conf = pa[i].max()
        b_conf = pb[i].max()
        a_lbl = pa[i].argmax()
        b_lbl = pb[i].argmax()

        # Rule 1: ALBERT strong, LR weak
        if a_conf >= 0.75 and b_conf < 0.60:
            lbl = a_lbl; conf = a_conf; source = "ALBERT"

        # Rule 2: LR strong, ALBERT weak
        elif b_conf >= 0.75 and a_conf < 0.60:
            lbl = b_lbl; conf = b_conf; source = "LR"

        # Rule 3: both agree → choose higher confidence
        elif a_lbl == b_lbl:
            if a_conf >= b_conf:
                lbl = a_lbl; conf = a_conf; source = "ALBERT"
            else:
                lbl = b_lbl; conf = b_conf; source = "LR"

        # Rule 4: disagree → choose confidence closer to 0.80
        else:
            target = 0.80
            lbl = a_lbl if abs(a_conf - target) <= abs(b_conf - target) else b_lbl
            conf = a_conf if lbl == a_lbl else b_conf
            source = "ALBERT" if lbl == a_lbl else "LR"

        final.append({
            "text": t,
            "label": id2label[lbl],
            "confidence": float(conf),
            "source": source
        })

    return final

