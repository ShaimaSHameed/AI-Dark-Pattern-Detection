    raw_idx = np.argmax(avg_probs, axis=1)

    results = []
    for text, pred_idx, prob_row in zip(texts, raw_idx, avg_probs):
        conf = float(prob_row[pred_idx])
        results.append({
            "prediction": le.classes_[pred_idx],
            "confidence": conf
        })
    return results


