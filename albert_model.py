def neutral_rewrite_openrouter(text):
    # Step 1 — classify with hybrid model
    pred = hybrid_predict([text])[0]
    label = pred["label"]
    conf  = pred["confidence"]

    # If already neutral → no need to rewrite
    if label == "neutral":
        return {
            "original": text,
            "detected_label": label,
            "confidence": conf,
            "rewritten": text,
            "note": "Already neutral."
        }

    # Step 2 — rewrite using OpenRouter
    neutral_prompt = f"""
Rewrite the following text into a neutral, non-biased, non-harmful version.
Remove emotional manipulation, brand favoritism, sneaking, sycophancy, anthropomorphization, or user-retention bias.

Text: "{text}"
"""

    rewritten = call_openrouter(neutral_prompt)

    return {
        "original": text,
        "detected_label": label,
        "confidence": conf,
        "rewritten": rewritten,
        "note": "Rewritten via OpenRouter LLM."
    }

