def apply_neutral_override(avg_probs, le, neutral_label="neutral",
                           conf_threshold=0.55,
                           margin_threshold=0.15,
                           unsure_threshold=0.50):
    """
    avg_probs: (N, num_classes) averaged probability matrix
    le: LabelEncoder
    Returns corrected labels based on neutral override logic.
    """

    corrected_labels = []
    neutral_idx = list(le.classes_).index(neutral_label)

    for prob_row in avg_probs:
        # Raw model decision
        top_idx = np.argmax(prob_row)
        top_label = le.classes_[top_idx]
        top_conf = prob_row[top_idx]

        neutral_conf = prob_row[neutral_idx]

        # 1) Hard confidence threshold
        if top_label != neutral_label and top_conf < conf_threshold:
            corrected_labels.append(neutral_label)
            continue

        # 2) Margin rule: predicted dark is too close to neutral
        if top_label != neutral_label:
            margin = top_conf - neutral_conf
            if margin < margin_threshold:
                corrected_labels.append(neutral_label)
                continue

        # 3) Unsure prediction fallback
        if top_conf < unsure_threshold:
            corrected_labels.append(neutral_label)
            continue

