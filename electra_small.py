def extract_sentiment_features(texts_list):
    features = []
    for t in tqdm(texts_list, desc="Sentiment"):
        tb = TextBlob(t)
        vd = vader.polarity_scores(t)
        features.append([
            tb.sentiment.polarity, tb.sentiment.subjectivity,
            vd['neg'], vd['neu'], vd['pos'], vd['compound']
        ])
    return np.array(features, dtype=np.float32)

def batch_encode_texts(texts_list, batch_size=32):
    all_embeddings = []
    with torch.no_grad():
        for i in tqdm(range(0, len(texts_list), batch_size), desc="Embeddings"):
            batch = texts_list[i:i+batch_size]
            enc = tokenizer(batch, padding=True, truncation=True,
                           return_tensors="pt", max_length=256)
            input_ids = enc['input_ids'].to(device)
            attention_mask = enc['attention_mask'].to(device)
            out = electra_model(input_ids=input_ids, attention_mask=attention_mask)
            last_hidden = out.last_hidden_state
            mask = attention_mask.unsqueeze(-1).expand(last_hidden.size()).float()
            summed = torch.sum(last_hidden * mask, dim=1)
            counts = torch.clamp(mask.sum(dim=1), min=1e-9)
            mean_pooled = (summed / counts).cpu().numpy()
            all_embeddings.append(mean_pooled)
    return np.vstack(all_embeddings)

def extract_all_features(texts_list):
    """Extract combined sentiment + embedding features."""
    sent_feats = extract_sentiment_features(texts_list)
    emb_feats = batch_encode_texts(texts_list)
    return np.concatenate([emb_feats, sent_feats], axis=1)

