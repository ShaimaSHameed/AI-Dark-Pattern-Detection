    # Get model predictions
    raw_outputs = predict_raw(texts)  # Now predict_raw is defined

    for txt, raw in zip(texts, raw_outputs):
        pred = raw["prediction"]
        conf = raw["confidence"]

        # 1) Anthropomorphization forced rule
        if contains_anthro(txt):
            corrected = "anthropomorphization"
