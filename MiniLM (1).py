def sentiment_features(texts):
    feats = []
    for t in tqdm(texts, desc="Sentiment"):
        tb = TextBlob(t)
        vd = vader.polarity_scores(t)
        feats.append([
            tb.sentiment.polarity,
            tb.sentiment.subjectivity,
            vd["neg"], vd["neu"], vd["pos"], vd["compound"]
        ])
    return np.array(feats, dtype=np.float32)

def encode_texts(texts, batch=32):
    all_vecs = []
    with torch.no_grad():
        for i in tqdm(range(0, len(texts), batch), desc="Embeddings"):
            batch_text = texts[i:i+batch]
            enc = tokenizer(
                batch_text,
                padding=True,
                truncation=True,
                max_length=256,
                return_tensors="pt"
            ).to(device)

            out = backbone(**enc)
            hidden = out.last_hidden_state
            mask = enc.attention_mask.unsqueeze(-1).expand(hidden.size()).float()

            summed = (hidden * mask).sum(dim=1)
            count = mask.sum(dim=1).clamp(min=1e-9)
            pooled = (summed / count).cpu().numpy()
            all_vecs.append(pooled)

    return np.vstack(all_vecs)

def extract_features(texts):
    emb = encode_texts(texts)
    sent = sentiment_features(texts)
    return np.concatenate([emb, sent], axis=1)

