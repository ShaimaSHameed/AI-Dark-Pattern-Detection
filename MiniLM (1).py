# -------------------------
# Load paraphrasing model
# -------------------------
PARA_MODEL = "Vamsi/T5_Paraphrase_Paws"
tokenizer_para = AutoTokenizer.from_pretrained(PARA_MODEL)
model_para = AutoModelForSeq2SeqLM.from_pretrained(PARA_MODEL)

def paraphrase(text, num=1):
    inputs = tokenizer_para.encode("paraphrase: " + text, return_tensors="pt", max_length=256, truncation=True)
    outputs = model_para.generate(
        inputs,
        max_length=256,
        num_return_sequences=num,
        do_sample=True,
        top_k=50,
        top_p=0.95
    )
    return [tokenizer_para.decode(o, skip_special_tokens=True) for o in outputs]

# -------------------------
# Light structured variation
# -------------------------
def light_variation(text):
    replacements = [
        ("can you", "could you"),
        ("please", "kindly"),
        ("explain", "describe"),
        ("tell me", "let me know"),
        ("i want", "i would like"),
        ("what is", "what's"),
        ("do you think", "would you say"),
    ]
    t = text.lower()
    for a, b in replacements:
        if a in t:
            t = t.replace(a, b)
            break
    return t

# -------------------------
# Minor punctuation noise
# -------------------------
def noise(text):
    options = [
        text + ".",
        text + "!",
        text.replace(",", ""),
        text.replace("?", "??"),
        text.lower(),
        text.capitalize()
    ]
    return random.choice(options)

