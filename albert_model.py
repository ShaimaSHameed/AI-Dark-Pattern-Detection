def extract_cls_embeddings(dataset):
    """Extract CLS embeddings for an HF Dataset using ALBERT encoder."""
    dataloader = DataLoader(dataset, batch_size=32, shuffle=False)
    embeddings = []

    with torch.no_grad():
        for batch in dataloader:
            input_ids = batch["input_ids"].to(device)
            attention_mask = batch["attention_mask"].to(device)

            # Run only the ALBERT encoder (not the classifier head)
            outputs = model_a.albert(
                input_ids=input_ids,
                attention_mask=attention_mask
            )

            # CLS token: first token of last hidden state
            cls_emb = outputs.last_hidden_state[:, 0, :]
            embeddings.append(cls_emb.cpu().numpy())

    return np.vstack(embeddings)


